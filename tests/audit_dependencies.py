def write(folder, rel, content):
    path = os.path.join(folder, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content if isinstance(content, str) else json.dumps(content))
    return path


class ParserTests(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix='audit-deps-')

    def tearDown(self):
        shutil.rmtree(self.dir, ignore_errors=True)

    def parse(self, name, content, sub=''):
        path = write(self.dir, os.path.join(sub, name), content)
        return {(p.name, p.version): (p.direct, p.dev, p.ecosystem) for p in audit.parse_lockfile(path, self.dir)}

    def test_package_lock_v3_direct_dev_nested_and_links(self):
        got = self.parse('package-lock.json', PACKAGE_LOCK_V3)
        self.assertEqual(got[('next', '16.2.10')], (True, False, 'npm'))
        self.assertEqual(got[('postcss', '8.4.31')], (False, False, 'npm'))
        self.assertEqual(got[('eslint', '9.0.0')], (True, True, 'npm'))
        self.assertEqual(got[('minimatch', '3.0.4')], (False, True, 'npm'))
        self.assertNotIn(('linked', None), got)
        self.assertEqual(len(got), 5)

    def test_package_lock_v1(self):
        got = self.parse('package-lock.json', PACKAGE_LOCK_V1)
        self.assertEqual(got[('next', '16.2.10')], (True, False, 'npm'))
        self.assertEqual(got[('postcss', '8.4.31')], (False, False, 'npm'))
        self.assertEqual(got[('eslint', '9.0.0')], (True, True, 'npm'))

    def test_pnpm_lock(self):
        got = self.parse('pnpm-lock.yaml', PNPM_LOCK)
        self.assertEqual(got[('next', '16.2.10')], (True, False, 'npm'))
        self.assertEqual(got[('postcss', '8.4.31')], (False, False, 'npm'))
        self.assertEqual(got[('@scope/pkg', '1.2.3')], (False, False, 'npm'))
        self.assertEqual(len(got), 3)

    def test_cargo_lock_skips_workspace_members(self):
        got = self.parse('Cargo.lock', CARGO_LOCK)
        self.assertEqual(list(got), [('quick-xml', '0.39.4')])
        self.assertEqual(got[('quick-xml', '0.39.4')][2], 'crates.io')

    def test_poetry_uv_composer_requirements(self):
        self.assertEqual(list(self.parse('poetry.lock', POETRY_LOCK)), [('tornado', '6.5.4')])
        self.assertEqual(list(self.parse('uv.lock', UV_LOCK)), [('requests', '2.19.0')])
        got = self.parse('composer.lock', COMPOSER_LOCK)
        self.assertEqual(got[('monolog/monolog', '2.0.0')], (True, False, 'Packagist'))
        self.assertEqual(got[('phpunit/phpunit', '9.0.0')], (True, True, 'Packagist'))
        got = self.parse('requirements.txt', REQUIREMENTS)
        self.assertEqual(sorted(got), [('numpy', '1.26.0'), ('requests', '2.19.0')])

    def test_find_lockfiles_skips_dependency_folders(self):
        write(self.dir, 'web/package-lock.json', PACKAGE_LOCK_V1)
        write(self.dir, 'web/node_modules/x/package-lock.json', PACKAGE_LOCK_V1)
        write(self.dir, 'tools/requirements-dev.txt', REQUIREMENTS)
        write(self.dir, '.venv/lib/requirements.txt', REQUIREMENTS)
        rels = [os.path.relpath(p, self.dir).replace(os.sep, '/') for p in audit.find_lockfiles(self.dir)]
        self.assertEqual(rels, ['tools/requirements-dev.txt', 'web/package-lock.json'])


class SeverityTests(unittest.TestCase):
    def test_cvss3_scores_match_the_calculator(self):
        for vector, expected in (
            ('CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:N/I:N/A:H', 7.5),
            ('CVSS:3.1/AV:N/AC:H/PR:N/UI:N/S:U/C:L/I:N/A:N', 3.7),
            ('CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:C/C:H/I:H/A:H', 10.0),
            ('CVSS:3.0/AV:L/AC:L/PR:L/UI:N/S:U/C:H/I:H/A:H', 7.8),
            ('CVSS:3.1/AV:N/AC:L/PR:L/UI:R/S:C/C:L/I:L/A:N', 5.4),
            ('CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:N/I:N/A:N', 0.0),
            ('CVSS:3.1/AV:P/AC:H/PR:H/UI:R/S:U/C:L/I:N/A:N', 1.6),
        ):
            with self.subTest(vector=vector):
                self.assertEqual(audit.cvss3_base_score(vector), expected)
        self.assertIsNone(audit.cvss3_base_score('CVSS:4.0/AV:N/AC:L/AT:N/PR:N/UI:N/VC:H/VI:H/VA:H/SC:N/SI:N/SA:N'))
        self.assertIsNone(audit.cvss3_base_score('garbage'))

    def test_level_sources(self):
        self.assertEqual(audit.level_of(ANSWERS['vulns']['GHSA-next-1']), 'critical')
        self.assertEqual(audit.level_of(ANSWERS['vulns']['RUSTSEC-2026-0194']), 'high')
        self.assertEqual(audit.level_of(ANSWERS['vulns']['RUSTSEC-2026-0001']), 'info')
        self.assertEqual(audit.level_of(ANSWERS['vulns']['PYSEC-2026-1']), 'low')
        self.assertEqual(audit.level_of(ANSWERS['vulns']['GHSA-requests']), 'unknown')
        self.assertEqual(audit.rank('unknown'), audit.rank('moderate'))


class RunTests(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix='audit-deps-')
        self.answers = write(self.dir, 'answers.json', ANSWERS)
        self.repo = os.path.join(self.dir, 'repo')
        os.makedirs(self.repo)

    def tearDown(self):
        shutil.rmtree(self.dir, ignore_errors=True)

    def run_tool(self, *args, repo=None):
        r = subprocess.run([sys.executable, TOOL, repo or self.repo, '--offline', self.answers, *args],
                           capture_output=True, text=True)
        return r.returncode, r.stdout, r.stderr

    def test_findings_lines_and_exit_code(self):
        write(self.repo, 'web/package-lock.json', PACKAGE_LOCK_V3)
        code, out, err = self.run_tool()
        self.assertEqual(code, 1, out + err)
        lines = out.splitlines()
        self.assertEqual(lines[0].split('\t')[:4], ['critical', 'GHSA-next-1', 'npm:next@16.2.10', 'direct'])
        self.assertIn('fixed: 16.2.11', lines[0])
        self.assertIn('web/package-lock.json', lines[0])
        self.assertIn('Next.js: Middleware bypass', lines[0])
        self.assertTrue(any(l.startswith('high\tGHSA-minimatch\tnpm:minimatch@3.0.4\ttransitive,dev') for l in lines), out)
        self.assertTrue(any(l.startswith('high\tGHSA-postcss\tnpm:postcss@8.4.31\ttransitive\t') for l in lines), out)
        self.assertIn('5 package(s) in 1 lockfile(s); 4 finding(s) (moderate 1, high 2, critical 1)', out)
        self.assertNotIn('npm audit', out)

    def test_level_threshold(self):
        write(self.repo, 'package-lock.json', PACKAGE_LOCK_V3)
        self.assertEqual(self.run_tool('--level', 'critical')[0], 1)
        write(self.repo, 'package-lock.json', {'lockfileVersion': 3, 'packages': {
            '': {}, 'node_modules/next': {'version': '16.2.10'}}})
        ANSWERS2 = dict(ANSWERS, queries={'npm:next@16.2.10': ['GHSA-next-2']})
        answers2 = write(self.dir, 'answers2.json', ANSWERS2)
        r = subprocess.run([sys.executable, TOOL, self.repo, '--offline', answers2], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stdout)  # moderate is below the default level high
        r = subprocess.run([sys.executable, TOOL, self.repo, '--offline', answers2, '--level', 'low'],
                           capture_output=True, text=True)
        self.assertEqual(r.returncode, 1)

    def test_aliases_collapse_into_one_finding_under_the_ghsa_id(self):
        write(self.repo, 'poetry.lock', POETRY_LOCK)
        code, out, _ = self.run_tool('--json')
        data = json.loads(out)
        self.assertEqual([f['id'] for f in data['findings']], ['GHSA-tornado'])
        self.assertEqual(data['findings'][0]['aliases'], ['CVE-2026-1', 'PYSEC-2026-1'])
        self.assertEqual(data['findings'][0]['level'], 'low')
        self.assertEqual(code, 0)

    def test_alias_families_merge_whatever_the_id_order(self):
        # A{A}, C{C}, B{A,C}: B bridges A and C, which came first; one finding, not two
        answers = dict(ANSWERS, queries={'PyPI:tornado@6.5.4': ['GHSA-aaaa', 'PYSEC-cccc', 'CVE-2026-bbbb']},
                       vulns={'GHSA-aaaa': ghsa('GHSA-aaaa', 'LOW', 'tornado', 'PyPI', '6.5.6'),
                              'PYSEC-cccc': ghsa('PYSEC-cccc', None, 'tornado', 'PyPI', '6.5.6'),
                              'CVE-2026-bbbb': ghsa('CVE-2026-bbbb', None, 'tornado', 'PyPI', '6.5.6',
                                                    aliases=['GHSA-aaaa', 'PYSEC-cccc'])})
        path = write(self.dir, 'alias.json', answers)
        write(self.repo, 'poetry.lock', POETRY_LOCK)
        r = subprocess.run([sys.executable, TOOL, self.repo, '--offline', path, '--json'], capture_output=True, text=True)
        data = json.loads(r.stdout)
        self.assertEqual([f['id'] for f in data['findings']], ['GHSA-aaaa'])
        self.assertEqual(data['findings'][0]['aliases'], ['CVE-2026-bbbb', 'PYSEC-cccc'])

    def test_rustsec_info_and_cvss_levels(self):
        write(self.repo, 'Cargo.lock', CARGO_LOCK)
        code, out, _ = self.run_tool()
        self.assertEqual(code, 1)
        self.assertIn('high\tRUSTSEC-2026-0194\tcrates.io:quick-xml@0.39.4\ttransitive\tfixed: 0.41.0', out)
        self.assertIn('info\tRUSTSEC-2026-0001\tcrates.io:quick-xml@0.39.4\ttransitive\tfixed: none', out)

    def test_several_lockfiles_and_unknown_severity(self):
        write(self.repo, 'api/composer.lock', COMPOSER_LOCK)
        write(self.repo, 'ml/uv.lock', UV_LOCK)
        code, out, _ = self.run_tool('--level', 'moderate')
        self.assertEqual(code, 1)
        self.assertIn('high\tGHSA-monolog\tPackagist:monolog/monolog@2.0.0\tdirect\tfixed: 2.0.1\tapi/composer.lock', out)
        self.assertIn('unknown\tGHSA-requests\tPyPI:requests@2.19.0', out)
        self.assertIn('3 package(s) in 2 lockfile(s); 2 finding(s) (high 1, unknown 1)', out)

    def test_no_lockfile_and_usage_errors(self):
        code, out, _ = self.run_tool()
        self.assertEqual(code, 0)
        self.assertIn('no lockfile found', out)
        self.assertEqual(subprocess.run([sys.executable, TOOL], capture_output=True).returncode, 2)
        self.assertEqual(subprocess.run([sys.executable, TOOL, self.repo, '--bogus'], capture_output=True).returncode, 2)
        write(self.repo, 'package-lock.json', '{not json')
        code, _, err = self.run_tool()
        self.assertEqual(code, 2)
        self.assertIn('cannot parse package-lock.json', err)

    def test_malformed_answer_is_a_failed_audit(self):
        write(self.repo, 'package-lock.json', PACKAGE_LOCK_V3)
        broken = write(self.dir, 'broken.json', dict(ANSWERS, vulns={}))  # ids without records
        r = subprocess.run([sys.executable, TOOL, self.repo, '--offline', broken],
                           capture_output=True, text=True)
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
        self.assertIn('unexpected answer', r.stderr)

    def test_npm_audit_uses_the_public_registry(self):
        result = subprocess.CompletedProcess([], 0, '{"vulnerabilities": {}}', '')
        with unittest.mock.patch.object(audit.shutil, 'which', return_value='/usr/bin/npm'), \
                unittest.mock.patch.object(audit.subprocess, 'run', return_value=result) as run:
            audit.npm_audit('.')
        self.assertIn('--registry=https://registry.npmjs.org/', run.call_args.args[0])

    def test_this_repository_has_no_lockfile(self):
        code, out, _ = self.run_tool(repo=ROOT)
        self.assertEqual(code, 0)
        self.assertIn('no lockfile found', out)


class UpgradeTests(unittest.TestCase):
    TODAY = '2026-10-25'

    def test_version_and_cycle_helpers(self):
        self.assertEqual(audit.version_tuple('16.2.10'), (16, 2, 10))
        self.assertEqual(audit.version_tuple('v20'), (20,))
        self.assertEqual(audit.version_tuple('1.0.0-rc.1+build'), (1, 0, 0))
        self.assertEqual(audit.version_tuple('latest'), ())
        cycles = ANSWERS['eol']['python']
        self.assertEqual(audit.cycle_for(cycles, '3.9.18')['cycle'], '3.9')
        self.assertIsNone(audit.cycle_for(cycles, '3.12.1'))
        self.assertEqual(audit.cycle_for(ANSWERS['eol']['nodejs'], '20.19.0')['cycle'], '20')
        self.assertEqual(audit.support_status(cycles[1], self.TODAY), ('eol', 'support ended 2025-10-31'))
        self.assertEqual(audit.support_status(cycles[0], self.TODAY), ('supported', 'supported until 2029-10-31'))
        self.assertEqual(audit.support_status({'cycle': '16', 'eol': False, 'lts': True}, self.TODAY),
                         ('supported', 'supported, no end date (LTS)'))
        self.assertEqual(audit.support_status(None, self.TODAY), ('unknown', ''))

    def test_runtimes_from_package_json_and_version_files(self):
        d = tempfile.mkdtemp(prefix='audit-rt-')
        try:
            write(d, 'package.json', {'engines': {'node': '>=20.11'}})
            write(d, '.python-version', '3.9.18\n')
            self.assertEqual(audit.runtimes(d), [('nodejs', '20.11', 'package.json engines.node'),
                                                 ('python', '3.9.18', '.python-version')])
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def test_upgrade_rows_and_states(self):
        packages = [audit.Package('npm', 'next', '16.2.10', True, False, 'package-lock.json'),
                    audit.Package('npm', 'left-pad', '1.3.0', True, False, 'package-lock.json'),
                    audit.Package('npm', 'eslint', '9.0.0', True, True, 'package-lock.json'),
                    audit.Package('npm', 'postcss', '8.4.31', False, False, 'package-lock.json'),
                    audit.Package('PyPI', 'numpy', '1.26.0', True, False, 'requirements.txt'),
                    audit.Package('PyPI', 'requests', '2.19.0', True, False, 'requirements.txt'),
                    audit.Package('crates.io', 'quick-xml', '0.39.4', True, False, 'Cargo.lock')]
        d = tempfile.mkdtemp(prefix='audit-up-')
        try:
            answers = write(d, 'a.json', ANSWERS)
            rows = audit.upgrades(packages, [('nodejs', '18.20', '.nvmrc'), ('deno', '2.0', '.dvmrc')],
                                  audit.Offline(answers), self.TODAY)
        finally:
            shutil.rmtree(d, ignore_errors=True)
        by = {(r['ecosystem'], r['name']): r for r in rows}
        self.assertEqual(by[('npm', 'eslint')]['state'], 'eol')
        self.assertEqual(by[('runtime', 'nodejs')]['state'], 'eol')
        self.assertEqual(by[('runtime', 'nodejs')]['note'], 'support ended 2025-04-30')
        self.assertEqual(by[('npm', 'next')]['state'], 'behind')
        self.assertEqual(by[('npm', 'next')]['note'], 'supported, no end date (LTS)')
        self.assertEqual(by[('PyPI', 'numpy')]['state'], 'major-behind')
        self.assertEqual(by[('npm', 'left-pad')]['state'], 'current')
        self.assertEqual(by[('PyPI', 'requests')]['state'], 'unknown')
        self.assertEqual(by[('runtime', 'deno')]['state'], 'unknown')
        self.assertNotIn(('npm', 'postcss'), by)      # transitive: no advice
        self.assertNotIn(('crates.io', 'quick-xml'), by)  # no crates.io lookup
        self.assertEqual([r['state'] for r in rows][:2], ['eol', 'eol'])

    def test_upgrades_in_the_command_output_and_exit_code(self):
        d = tempfile.mkdtemp(prefix='audit-up-')
        try:
            answers = write(d, 'a.json', dict(ANSWERS, queries={}))
            repo = os.path.join(d, 'repo')
            write(repo, 'package-lock.json', {'lockfileVersion': 3, 'packages': {
                '': {'dependencies': {'left-pad': '1.3.0'}, 'devDependencies': {'eslint': '9.0.0'}},
                'node_modules/left-pad': {'version': '1.3.0'}, 'node_modules/eslint': {'version': '9.0.0', 'dev': True}}})
            write(repo, '.nvmrc', '24\n')
            r = subprocess.run([sys.executable, TOOL, repo, '--offline', answers, '--upgrades'], capture_output=True, text=True)
            self.assertEqual(r.returncode, 1, r.stdout)  # eol ranks as high
            self.assertIn('eol\tnpm:eslint@9.0.0,dev\tlatest 10.1.0\tsupport ended 2026-08-06\tpackage-lock.json', r.stdout)
            self.assertIn('current\truntime:nodejs@24\tlatest ?\tsupported until 2028-04-30\t.nvmrc', r.stdout)
            self.assertIn('upgrades: 3 direct package(s) and runtime(s) checked (eol 1, current 2)', r.stdout)
            r = subprocess.run([sys.executable, TOOL, repo, '--offline', answers, '--upgrades', '--level', 'critical'],
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 0)
            # a major behind is advice: the pre-deploy run at --level moderate must not fail on it
            write(repo, 'package-lock.json', {'lockfileVersion': 3, 'packages': {
                '': {'dependencies': {'numpy-js': '1.0.0'}}, 'node_modules/numpy-js': {'version': '1.0.0'}}})
            answers_major = write(d, 'b.json', dict(ANSWERS, queries={}, latest={'npm:numpy-js@1.0.0': '2.0.0'}))
            r = subprocess.run([sys.executable, TOOL, repo, '--offline', answers_major, '--upgrades', '--level', 'moderate'],
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stdout)
            self.assertIn('major-behind\tnpm:numpy-js@1.0.0\tlatest 2.0.0', r.stdout)
            r = subprocess.run([sys.executable, TOOL, repo, '--offline', answers_major, '--upgrades', '--level', 'low'],
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 1)
            r = subprocess.run([sys.executable, TOOL, repo, '--offline', answers], capture_output=True, text=True)
            self.assertNotIn('upgrades:', r.stdout)
        finally:
            shutil.rmtree(d, ignore_errors=True)


