def ghsa(vid, severity, name, ecosystem, fixed, aliases=(), summary='s', cvss=None):
    rec = {'id': vid, 'summary': summary, 'aliases': list(aliases),
           'affected': [{'package': {'name': name, 'ecosystem': ecosystem},
                         'ranges': [{'type': 'ECOSYSTEM', 'events': [{'introduced': '0'}, {'fixed': fixed}]}]}]}
    if severity:
        rec['database_specific'] = {'severity': severity}
    if cvss:
        rec['severity'] = [{'type': 'CVSS_V3', 'score': cvss}]
    return rec


